#include <stdlib.h>
/**
* op_add - Adds two integers
* @a: First integer.
* @b: Second integer.
*
* Return: Sum of the two integers.
*/
int op_add(int a, int b)
{
	return (a + b);
}

/**
 * op_sub - Calculates the difference between 2 integers.
 * @a: First integer.
 * @b: Second integer, to subtract.
 *
 * Return: The difference between the two integers.
 */
int op_sub(int a, int b)
{
	return (a - b);
}

/**
 * op_mul - Calculates the product of 2  integers.
 * @a: First integer.
 * @b: Second integer.
 *
 * Return: The product of the two integers.
 */
int op_mul(int a, int b)
{
	return (a * b);
}

/**
 * op_div - Calculates the quotient of 2 integers.
 * @a: First integer.
 * @b: Second integer.
 *
 * Return: The quotient.
 */
int op_div(int a, int b)
{
	return (a / b);
}

/**
 * op_mod - Calculates the remainder from division of 2 integers.
 * @a: First integer.
 * @b: Second integer.
 *
 * Return: The remainder from the division.
 */
int op_mod(int a, int b)
{
	return (a % b);
}
